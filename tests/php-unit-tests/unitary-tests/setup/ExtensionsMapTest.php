	public function testAddExtensionAlwaysKeepsNewestVersion(): void
	{
		$oExtensionsMap = iTopExtensionsMapFake::createFromArray([]);

		$oExtensionV1 = $this->GivenExtension('my-ext', '1.0.0');
		$oExtensionsMap->AddExtension($oExtensionV1);
		$this->assertSame($oExtensionV1, $oExtensionsMap->GetFromExtensionCode('my-ext'));
		$this->assertEquals(['my-ext/1.0.0'], array_keys($oExtensionsMap->GetAllExtensions()));

		$oExtensionV3 = $this->GivenExtension('my-ext', '3.0.0');
		$oExtensionsMap->AddExtension($oExtensionV3);
		$this->assertSame($oExtensionV3, $oExtensionsMap->GetFromExtensionCode('my-ext'));
		$this->assertEquals(['my-ext/3.0.0'], array_keys($oExtensionsMap->GetAllExtensions()));

		$oExtensionV2 = $this->GivenExtension('my-ext', '2.0.0');
		$oExtensionsMap->AddExtension($oExtensionV2);
		$this->assertSame($oExtensionV3, $oExtensionsMap->GetFromExtensionCode('my-ext'));
		$this->assertEquals(['my-ext/3.0.0'], array_keys($oExtensionsMap->GetAllExtensions()));
	}

	public function testAddExtensionReplaceRemovedExtensions(): void
	{
		$oExtensionsMap = iTopExtensionsMapFake::createFromArray([]);

		$oExtensionV3Removed = $this->GivenExtension('my-ext', '3.0.0');
		$oExtensionV3Removed->bRemovedFromDisk = true;
		$oExtensionsMap->AddExtension($oExtensionV3Removed);
		$this->assertSame($oExtensionV3Removed, $oExtensionsMap->GetFromExtensionCode('my-ext'));
		$this->assertEquals(['my-ext/3.0.0'], array_keys($oExtensionsMap->GetAllExtensions()));

		$oExtensionV2 = $this->GivenExtension('my-ext', '2.0.0');
		$oExtensionsMap->AddExtension($oExtensionV2);
		$this->assertSame($oExtensionV2, $oExtensionsMap->GetFromExtensionCode('my-ext'));
		$this->assertEquals(['my-ext/2.0.0'], array_keys($oExtensionsMap->GetAllExtensions()));
	}

	private function GiveExtensionMapWithAllTypeOfExtensions(): iTopExtensionsMap
	{
		$oExtensionsMap = iTopExtensionsMap::GetExtensionsMap();
		$this->SetNonPublicProperty($oExtensionsMap, 'aInstalledExtensions', []);
		$this->SetNonPublicProperty($oExtensionsMap, 'aExtensions', []);

		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("installed_ext1", "123", true, iTopExtension::SOURCE_REMOTE, true, []),
			'aInstalledExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("installed_notvisible", "123", false, iTopExtension::SOURCE_REMOTE, true, []),
			'aInstalledExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("installed_ext_in_package", "123", true, iTopExtension::SOURCE_WIZARD, true, []),
			'aInstalledExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("installed_ext_with_deps_issues", "123", true, iTopExtension::SOURCE_REMOTE, true, ["aa"]),
			'aInstalledExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("ext1", "123", true, iTopExtension::SOURCE_REMOTE, true, []),
			'aExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("notvisible", "123", false, iTopExtension::SOURCE_REMOTE, true, []),
			'aExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("ext_in_package", "123", true, iTopExtension::SOURCE_WIZARD, true, []),
			'aExtensions'
		);
		$this->AddExtension(
			$oExtensionsMap,
			$this->GivenExtension("ext_with_deps_issues", "123", true, iTopExtension::SOURCE_REMOTE, true, ["aa"]),
			'aExtensions'
		);

		return $oExtensionsMap;
	}

	private function GivenExtension(string $sCode, string $sVersion, bool $bVisible = true, string $sSource = iTopExtension::SOURCE_REMOTE, bool $bMandatory = false, array $aMissingDependencies = []): iTopExtension
	{
		$oExt = new iTopExtension();
		$oExt->sCode = $sCode;
		$oExt->sLabel = "LABEL_".$sCode;
		$oExt->sVersion = $sVersion;
		$oExt->bVisible = $bVisible;
		$oExt->sSource = $sSource;
		$oExt->aMissingDependencies = $aMissingDependencies;
		$oExt->bMandatory = $bMandatory;
		return $oExt;
	}

	private function AddExtension(iTopExtensionsMap $oExtensionsMap, iTopExtension $oExt, string $mapKeyInItopExtensionMap)
	{
		$this->InvokeNonPublicMethod(iTopExtensionsMap::class, 'AddExtension', $oExtensionsMap, [$oExt]);
		$aMap = $this->GetNonPublicProperty($oExtensionsMap, $mapKeyInItopExtensionMap);
		$aMap[$oExt->sCode.'/'.$oExt->sVersion] = $oExt;
		$this->SetNonPublicProperty($oExtensionsMap, $mapKeyInItopExtensionMap, $aMap);
	}

